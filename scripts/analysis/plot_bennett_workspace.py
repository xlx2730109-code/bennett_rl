"""Single-leg tip workspace of Urdf_Bennett_3 -- reproduction of Fig. 5 in
"Overconstrained coaxial design of robotic legs with omni-directional
locomotion" (Gu et al., Mechanism and Machine Theory 176, 2022).

Mechanism structure (verified numerically, see outputs/_mobility_check.py):
  * The closed loop base->thigh(q1)->calf(q2)->_3->(spherical)->_2->(_1)->thigh
    has mobility 1 once the thigh frame is fixed: for a GIVEN q2 the passive
    angles (q3,q4,q5) and the tip position in the thigh frame are uniquely
    determined -- independent of q1 (q5 = q2 holds exactly).
  * q1 therefore only rotates the whole leg about the coaxial drive axis
    U1 = (0, 1, 1)/sqrt(2): the workspace is the SURFACE OF REVOLUTION of the
    1-D generator curve g(q2) about the drive axis -- exactly the generation
    principle stated in the paper ("generated by rotating a line in 3D space",
    their generator is near-semicircular -> half-cut-away torus).
  * The physical branch is 4*pi periodic in the configuration but the TIP locus
    closes after one period to within 3 mm (period-3 arc = period-1 arc exactly),
    so one period of g closes into a ring for plotting.

Display orientation: the FR leg is plotted (exact mirror of FL in y, verified
against bennett_1.xml: FR_thigh axis (0,-1,1)/sqrt2, identical joint ranges), so
the drive axis U = (0,-1,1)/sqrt2 runs UPPER-LEFT to LOWER-RIGHT in the y-z side
view -- the same orientation as the paper's z1 (Fig. 4) and its side-view band.

Sweeps
  generator : q2 over one full period (continuation from the straight assembly
              at q2 = 0, with random-restart rescue through the steep region)
  surface   : q1 over a full cycle applied analytically (exact, not re-solved)
  fig5_workspace          : three-view figure; isometric is a half-cut-away
                            (lower half of the revolution kept, cut edges show
                            the generator curve), side/front views show the
                            full projection like the paper
  fig5_workspace_full     : same figure with the full-torus isometric
  fig5b_workspace_limited : hardware-limited usable patch (thigh +/-0.8 rad,
                            calf -0.9..+0.55 rad) and the rest-pose tip

All coordinates are hip frame (origin = thigh joint centre, robot body axes),
in millimetres. Geometry is taken from sim2sim/models/bennett_1/bennett_1.xml.

Usage:
  python scripts/analysis/plot_bennett_workspace.py                 # cached scan + plot
  python scripts/analysis/plot_bennett_workspace.py --rescan        # re-scan generator
  python scripts/analysis/plot_bennett_workspace.py --n_gen 1441    # denser generator
"""

