    norm = plt.Normalize(np.nanmin(tips[:, :, 2]), np.nanmax(tips[:, :, 2]))
    lim = nice_lim(tips)

    # hardware-limited patch: q1 in [-0.8, 0.8], calf over [-0.9, 0.55] (wraps at 2pi)
    n1b, n = 49, len(q2s)
    q1b = np.linspace(-THIGH_LIMIT, THIGH_LIMIT, n1b)
    dq = 2.0 * np.pi / n
    ja = int(round((CALF_LIMITS[1] - Q2_START) / dq))          # q2 = +0.55
    jb = int(round(((CALF_LIMITS[0] - Q2_START) % (2 * np.pi)) / dq))  # q2 = -0.9 (wrapped)
    Gc = np.vstack([g_tips / 1000.0, g_tips[:1] / 1000.0])     # closed generator, m
    j_idx = np.concatenate([np.arange(jb, n + 1), np.arange(1, ja + 1)])
    band = np.empty((n1b, len(j_idx), 3))
    for i, q1 in enumerate(q1b):
        R = rot_axis(U_PLOT, q1)[:3, :3]
        band[i] = (R @ Gc[j_idx].T).T
    band *= 1000.0
    # boundary curves
    b_lo, b_hi = band[0], band[-1]                              # q1 = -0.8 / +0.8 arcs
    e_lo, e_hi = band[:, 0], band[:, -1]                        # q2 = -0.9 / +0.55 arcs

    # rest pose (standing defaults: thigh 0.08, calf -0.16), displayed on the
    # mirrored FR leg
