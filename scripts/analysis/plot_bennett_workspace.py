# ---------------------------------------------------------------------- main --
def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--n_gen", type=int, default=721, help="generator points per q2 period")
    parser.add_argument("--n_rot", type=int, default=280, help="revolution steps over full q1 cycle")
    parser.add_argument("--rescan", action="store_true")
    args = parser.parse_args()

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    cache = OUT_DIR / "workspace_generator.npz"
    if cache.exists() and not args.rescan:
        d = np.load(cache)
        q2s, g_tips, g_pass, g_errs = d["q2s"], d["g_tips"], d["g_pass"], d["g_errs"]
        print(f"loaded cached generator {cache.name} (n={len(q2s)})")
    else:
        print(f"scanning generator, {args.n_gen} points over one q2 period ...")
        q2s, g_tips, g_pass, g_errs = scan_generator(args.n_gen)
        np.savez_compressed(cache, q2s=q2s, g_tips=g_tips, g_pass=g_pass, g_errs=g_errs)
        print(f"  cached -> {cache}")

    # display orientation: mirror y -> FR leg (exact mirror, see module docstring)
    g_tips = g_tips * MIR

    q1s, tips = build_surface(g_tips, args.n_rot)
    validate_surface(q2s, g_pass)
    d_ax = tips - np.einsum("ijk,k->ij", tips, U_PLOT)[..., None] * U_PLOT
    print(f"tip reach: |tip| in [{np.linalg.norm(tips, axis=2).min():.0f}, "
          f"{np.linalg.norm(tips, axis=2).max():.0f}] mm, axis radius in "
          f"[{np.linalg.norm(d_ax, axis=2).min():.0f}, {np.linalg.norm(d_ax, axis=2).max():.0f}] mm")

