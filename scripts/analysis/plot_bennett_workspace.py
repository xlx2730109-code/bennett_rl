Q2_START = 0.0           # straight assembly, passive = (0, 0, 0)


# ------------------------------------------------------------------ scanning --
def solve_tracked(q2, x_warm, x_pred, rng, tip_pred=None):
    """Closure solve that stays on the physical sheet through the steep
    multi-root zone: continuation first, then restarts at growing sigma,
    always keeping the root closest to the linear prediction x_pred."""
    cands = []
    x, e, foot = solve_passive(0.0, q2, x_warm)
    if e < 1e-10:
        cands.append((np.linalg.norm(x - x_pred), x, foot))
    for sig in (0.3, 0.8, 1.5, 2.5):
        for _ in range(10):
            x0 = x_warm + rng.normal(0.0, sig, 3)
            x2, e2, f2 = solve_passive(0.0, q2, x0)
            if e2 < 1e-10:
                d = np.linalg.norm(x2 - x_pred)
                cands.append((d, x2, f2))
    if not cands:
        return None, None
    cands.sort(key=lambda c: c[0])
    return cands[0][1], cands[0][2]


def scan_generator(n=721):
    """One full period of the generator curve g(q2), hip frame, mm."""
    q2s = Q2_START + np.arange(n) * (2.0 * np.pi / n)
    rng = np.random.default_rng(11)
    g_tips = np.full((n, 3), np.nan)
    g_pass = np.full((n, 3), np.nan)
    g_errs = np.full(n, np.nan)
    x_hist = [np.zeros(3)]
    t0 = time.time()
    n_rescue = 0
    for j, q2 in enumerate(q2s):
        x_warm = x_hist[-1]
        x_pred = 2.0 * x_hist[-1] - x_hist[-2] if len(x_hist) > 1 else x_warm
        x, foot = solve_tracked(q2, x_warm, x_pred, rng)
        if x is None:
            print(f"  FAILED at q2={q2:.4f}")
            continue
        if not np.allclose(x, x_warm, atol=1e-9):
            n_rescue += 1
        x_hist.append(x)
        g_tips[j] = foot * 1000.0
        g_pass[j] = x
        g_errs[j] = 0.0
        if (j + 1) % 120 == 0:
            print(f"  gen {j + 1}/{n}  ({time.time() - t0:.0f} s)")
    print(f"generator done in {time.time() - t0:.0f} s, steps off the bare continuation: {n_rescue}")
    step = np.linalg.norm(np.diff(g_tips, axis=0), axis=1)
    k = int(np.argmax(step))
    print(f"max generator step {step.max():.2f} mm at q2={q2s[k]:.3f}")
    print(f"max |q5 - q2| over branch: {np.nanmax(np.abs(g_pass[:, 2] - q2s)):.2e} rad")
    x_end, _, foot_end = solve_passive(0.0, q2s[-1] + 2 * np.pi / n, g_pass[-1])
    print(f"period closure: tip diff {np.linalg.norm(foot_end * 1000 - g_tips[0]):.4f} mm, "
          f"passive diff {np.max(np.abs(x_end - g_pass[0])):.2e} rad")
    return q2s, g_tips, g_pass, g_errs


def build_surface(g_tips, n_rot=280):
    """Apply the q1 revolution analytically: tips(q1, q2) = R(U_PLOT, q1) g(q2),
    with closed seams in both parameters."""
    q1s = np.linspace(0.0, 2.0 * np.pi, n_rot + 1)
    G = np.vstack([g_tips / 1000.0, g_tips[:1] / 1000.0])  # closed, metres
    tips = np.empty((len(q1s), len(G), 3))
    for i, q1 in enumerate(q1s):
        R = rot_axis(U_PLOT, q1)[:3, :3]
        tips[i] = (R @ G.T).T
    return q1s, tips * 1000.0


def halfcut_start(tips):
    """Start angle a0 of the pi-window of the revolution whose surface has the
    lowest mean z (the 'lower half' cut-away window)."""
    zbar = np.nanmean(tips[:-1, :, 2], axis=1)      # mean tip z at each q1 step
    n = len(zbar)
    w = n // 2                                       # window = half revolution
    c = np.concatenate([[0.0], np.cumsum(np.tile(zbar, 2))])
    means = (c[np.arange(n) + w] - c[np.arange(n)]) / w
    return 2.0 * np.pi * int(np.argmin(means)) / n


def validate_surface(q2s, g_pass, n_check=80):
    """Random (q1, q2) points: the passive solution must be g_pass(q2) itself
    (closure independent of q1) -- hard check of the revolution construction."""
    rng = np.random.default_rng(5)
    ok, max_dev, max_e = 0, 0.0, 0.0
    for _ in range(n_check):
        q1 = rng.uniform(-2 * np.pi, 2 * np.pi)
        j = int(rng.integers(0, len(q2s)))
        x, e, _ = solve_passive(q1, q2s[j], g_pass[j])
        max_e = max(max_e, e)
        max_dev = max(max_dev, float(np.max(np.abs(x - g_pass[j]))))
        ok += e < 1e-11 and np.linalg.norm(x - g_pass[j]) < 1e-7
    print(f"validation: {ok}/{n_check} exact (max passive dev {max_dev:.1e} rad, "
          f"max closure {max_e:.1e} m)")


# ------------------------------------------------------------------- drawing --
def style3d(ax):
    ax.set_facecolor(SURFACE)
    for pane in (ax.xaxis.pane, ax.yaxis.pane, ax.zaxis.pane):
        pane.set_facecolor(SURFACE)
        pane.set_edgecolor(GRID)
    ax.tick_params(colors=INK, labelsize=7.5, pad=-1)
    for axis in (ax.xaxis, ax.yaxis, ax.zaxis):
        axis._axinfo["grid"].update({"color": GRID, "linewidth": 0.6})
        axis.line.set_color(MUTED)


def add_triad(ax, scale, zorder=None):
    for d in np.eye(3):
        ax.quiver(0, 0, 0, *(d * scale), color="#7b2d8b", linewidth=1.6,
                  arrow_length_ratio=0.12, zorder=zorder)


def add_axis3d(ax, lim):
    """Drive-axis z1 reference line through the hip origin, dashed, drawn
    behind the surface so it reads as sticking out at both ends."""
    L = 1.04 * lim
    u = U_PLOT
    ax.plot([-L * u[0], L * u[0]], [-L * u[1], L * u[1]], [-L * u[2], L * u[2]],
            color=INK2, linewidth=0.9, linestyle=(0, (5, 4)), alpha=0.95, zorder=0)
    ax.text(1.10 * L * u[0], 1.10 * L * u[1], 1.10 * L * u[2], "$z_1$",
            color=INK2, fontsize=8, ha="center", va="bottom")


def add_axis_side(ax, lim):
    """The same drive axis projected into the y-z side view: the upper-left to
    lower-right diagonal through the origin."""
    L = 1.04 * lim
    ax.plot([-L * U_PLOT[1], L * U_PLOT[1]], [-L * U_PLOT[2], L * U_PLOT[2]],
            color=INK2, linewidth=0.9, linestyle=(0, (5, 4)), alpha=0.95, zorder=0.5)
    ax.text(1.10 * L * U_PLOT[1], 1.10 * L * U_PLOT[2], "$z_1$",
            color=INK2, fontsize=8, ha="right", va="bottom")


def nice_lim(tips):
    return 50.0 * np.ceil(np.nanmax(np.abs(tips)) * 1.05 / 50.0)


def ortho_scatter(ax, tips, cmap, norm, stride=2, alpha=1.0):
    z = tips[::stride, ::stride, 2]
    pts = tips[::stride, ::stride, :2]
    order = np.argsort(z.ravel())
    ax.scatter(pts[:, :, 0].ravel()[order], pts[:, :, 1].ravel()[order],
               c=z.ravel()[order], s=0.8, cmap=cmap, norm=norm, linewidths=0,
               alpha=alpha, rasterized=True)


def ortho_fill(ax, tips, cmap, norm, xy=(1, 2), stride_q2=2):
    """Filled orthographic projection of the parametric surface onto a coordinate
    plane: tripcolor over the (q1, q2) grid -- no point-cloud moire."""
    i, j = xy
    P = tips[:, ::stride_q2, :]
    n1, n2 = P.shape[0], P.shape[1]
    xv = P[:, :, i].ravel()
    yv = P[:, :, j].ravel()
    zv = P[:, :, 2].ravel()
    idx = np.arange(n1 * n2).reshape(n1, n2)
    t1 = np.stack([idx[:-1, :-1], idx[1:, :-1], idx[1:, 1:]], axis=-1).reshape(-1, 3)
    t2 = np.stack([idx[:-1, :-1], idx[1:, 1:], idx[:-1, 1:]], axis=-1).reshape(-1, 3)
    ax.tripcolor(xv, yv, np.vstack([t1, t2]), zv, cmap=cmap, norm=norm,
                 shading="gouraud", rasterized=True, snap=False)


def style_ortho(ax, lim):
    ax.set_aspect("equal")
    ax.set_facecolor(SURFACE)
    for side in ax.spines.values():
        side.set_color(MUTED)
        side.set_linewidth(0.8)
    ax.grid(color=GRID, linewidth=0.6)
    ax.set_axisbelow(True)
    ax.tick_params(colors=INK, labelsize=7.5)
    ax.set_xlim(-lim, lim)
    ax.set_ylim(-lim, lim)


def three_view_fig():
    fig = plt.figure(figsize=(12.2, 5.9), facecolor=SURFACE, constrained_layout=True)
    gs = fig.add_gridspec(2, 2, width_ratios=[1.42, 1.0])
    ax3d = fig.add_subplot(gs[:, 0], projection="3d")
    ax_side = fig.add_subplot(gs[0, 1])
    ax_front = fig.add_subplot(gs[1, 1])
    return fig, ax3d, ax_side, ax_front


def finish_ortho(ax, title, lim):
    ax.set_title(title, fontsize=9.5, color=INK, loc="left")
    ax.set_xlabel("y (mm)" if "Side" in title else "x (mm)", fontsize=8.5, color=INK)
    ax.set_ylabel("z (mm)", fontsize=8.5, color=INK)
    style_ortho(ax, lim)


