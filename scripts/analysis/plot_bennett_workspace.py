    add_triad(ax3d, 0.22 * lim)
    style3d(ax3d)
    ax3d.set_xlabel("x (mm)", fontsize=8.5, color=INK)
    ax3d.set_ylabel("y (mm)", fontsize=8.5, color=INK)
